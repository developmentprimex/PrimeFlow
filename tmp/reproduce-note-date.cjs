const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('../frontend/node_modules/typescript');
const source = fs.readFileSync('frontend/src/components/px-notes-workspace.tsx', 'utf8');
const fn = source.match(/function taskDateKey\([\s\S]*?\n}/)[0];
const context = {};
vm.createContext(context);
vm.runInContext(ts.transpileModule(fn, {compilerOptions: {target: ts.ScriptTarget.ES2022}}).outputText, context);
const input = '2026-10-21T22:00:00+00:00';
console.log(JSON.stringify({input, pxNotes: context.taskDateKey(input), localDate: new Intl.DateTimeFormat('en-GB', {timeZone: 'Europe/Budapest'}).format(new Date(input))}));
